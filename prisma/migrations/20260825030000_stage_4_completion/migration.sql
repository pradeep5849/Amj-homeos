ALTER TYPE "OnboardingStatus" ADD VALUE 'NOT_CONFIGURED' BEFORE 'CANCELLED';

DROP TRIGGER IF EXISTS "Onboarding_terminal_guard" ON "DeviceOnboardingSession";
DROP FUNCTION IF EXISTS guard_onboarding_terminal_state();
CREATE FUNCTION guard_onboarding_transition() RETURNS trigger AS $$
BEGIN
  IF OLD."status" = NEW."status" THEN RETURN NEW; END IF;
  IF NOT (
    (OLD."status"='IDLE' AND NEW."status" IN ('PERMISSION_REQUIRED','SCANNING','CANCELLED','EXPIRED','UNSUPPORTED','NOT_CONFIGURED')) OR
    (OLD."status"='PERMISSION_REQUIRED' AND NEW."status" IN ('BLUETOOTH_DISABLED','SCANNING','CANCELLED','EXPIRED','UNSUPPORTED','NOT_CONFIGURED')) OR
    (OLD."status"='BLUETOOTH_DISABLED' AND NEW."status" IN ('PERMISSION_REQUIRED','CANCELLED','EXPIRED')) OR
    (OLD."status"='SCANNING' AND NEW."status" IN ('DEVICE_FOUND','FAILED','CANCELLED','EXPIRED','UNSUPPORTED','NOT_CONFIGURED')) OR
    (OLD."status"='DEVICE_FOUND' AND NEW."status" IN ('DEVICE_SELECTED','SCANNING','CANCELLED','EXPIRED')) OR
    (OLD."status"='DEVICE_SELECTED' AND NEW."status" IN ('PROVISIONING','CANCELLED','EXPIRED')) OR
    (OLD."status"='PROVISIONING' AND NEW."status" IN ('WAITING_FOR_NETWORK','REGISTERING','FAILED','CANCELLED','EXPIRED','NOT_CONFIGURED')) OR
    (OLD."status"='WAITING_FOR_NETWORK' AND NEW."status" IN ('REGISTERING','FAILED','CANCELLED','EXPIRED')) OR
    (OLD."status"='REGISTERING' AND NEW."status" IN ('SUCCESS','FAILED','EXPIRED'))
  ) THEN RAISE EXCEPTION 'invalid onboarding transition: % to %', OLD."status", NEW."status" USING ERRCODE='23514'; END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER "Onboarding_transition_guard" BEFORE UPDATE OF "status" ON "DeviceOnboardingSession" FOR EACH ROW EXECUTE FUNCTION guard_onboarding_transition();
